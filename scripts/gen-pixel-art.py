def rects(map_lines):
    out = []
    h = len(map_lines)
    for y, row in enumerate(map_lines):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            run = 1
            while x + run < len(row) and row[x + run] == ch:
                run += 1
            out.append(
                '<rect x="%d" y="%d" width="%d" height="1" fill="%s"/>'
                % (x, y, run, PALETTE[ch])
            )
            x += run
    return out, len(map_lines[0]), h


def sprite(name, map_lines, palette=None):
    pal = palette or PALETTE
    out = []
    w = len(map_lines[0])
    h = len(map_lines)
    for y, row in enumerate(map_lines):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            run = 1
            while x + run < len(row) and row[x + run] == ch:
                run += 1
            out.append(
                '<rect x="%d" y="%d" width="%d" height="1" fill="%s"/>'
                % (x, y, run, pal.get(ch, "#000"))
            )
            x += run
    return (
        "export function %s({ className, style }: { className?: string; style?: React.CSSProperties }) {\n"
        "  return (\n"
        '    <svg viewBox="0 0 %d %d" shapeRendering="crispEdges" className={className} style={style} aria-hidden="true">\n'
        "      <g>%s</g>\n"
        "    </svg>\n"
        "  );\n"
        "}\n" % (name, w, h, "".join(out))
    )


